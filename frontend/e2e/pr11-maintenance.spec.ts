test('Edit saves both rate modes and existing sessions retain their snapshotted rates', async ({ page, signIn }) => {
  await signIn(OWNER);
  const table = await apiPost<PoolTable>(page.request, '/api/v1/tables', { name: 'PR11 hourly', ratePerHour: 200 });
  const customers = await apiGet<Array<{ id: string }>>(page.request, '/api/v1/customer-types');
  const session = await apiPost<Session>(page.request, '/api/v1/sessions', { tableId: table.id, customerTypeId: customers[0]!.id });
  await page.goto('/admin/tables');
  await page.getByRole('button', { name: 'Actions for PR11 hourly', exact: true }).click();
  await expect(page.getByRole('menuitem', { name: /^Archive/ })).toHaveAttribute('aria-disabled', 'true');
  await expect(page.getByRole('menuitem', { name: /^Archive/ })).toContainText('Close the open session');
  await page.getByRole('menuitem', { name: 'Edit', exact: true }).click();
  await expect(page.getByLabel('Rate per hour', { exact: true })).toHaveValue('200');
  await page.getByLabel('Name', { exact: true }).fill('PR11 renamed');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  for (const mode of ['minute', 'hour']) {
    await page.reload();
    await page.getByRole('button', { name: 'Actions for PR11 renamed', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Edit', exact: true }).click();
    await expect(page.getByLabel(mode === 'minute' ? 'Rate per hour' : 'Rate per minute', { exact: true })).toHaveValue(mode === 'minute' ? '200' : '2.1234');
    await page.getByRole('button', { name: mode === 'minute' ? 'Per minute' : 'Per hour', exact: true }).click();
    const input = page.getByLabel(mode === 'minute' ? 'Rate per minute' : 'Rate per hour', { exact: true });
    await expect(input).toHaveValue('');
    await input.fill(mode === 'minute' ? '2.1234' : '250');
    await page.getByRole('button', { name: 'Save', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    const read = (await apiGet<FloorView>(page.request, '/api/v1/tables')).tables.find(t => t.id === table.id)!;
    expect([read.ratePerHour, read.ratePerMinute, read.effectiveRatePerHour]).toEqual(mode === 'minute' ? [null, 2.1234, 127.404] : [250, 4.1667, 250.002]);
    const old = await apiGet<Session>(page.request, `/api/v1/sessions/${session.id}`);
    expect(old.segments[0]!.ratePerMinute).toBe(3.3333);
  }
  await page.reload();
  await page.getByRole('button', { name: 'Rate details for PR11 renamed', exact: true }).click();
  await expect(page.getByRole('tooltip')).toContainText('₱4.1667');
  await expect(page.getByRole('tooltip')).toContainText('₱250.002');
  await expect(page.getByRole('tooltip')).not.toContainText('under');
  await apiPost(page.request, `/api/v1/sessions/${session.id}/close`, {});
  await page.reload();
  await page.getByRole('button', { name: 'Actions for PR11 renamed', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Archive', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Archive', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByLabel('Show archived').check();
  const row = page.getByRole('listitem').filter({ hasText: 'PR11 renamed' });
  await row.getByRole('button', { name: 'Restore', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Actions for PR11 renamed', exact: true })).toBeVisible();
});

test('staff edit, password reset, archive/restore and unused deletion retain their server behavior', async ({ page, signIn }) => {
  await signIn(OWNER);
  const user = await apiPost<StaffUser>(page.request, '/api/v1/users', { username: 'pr11-counter', fullName: 'PR11 Counter', role: 'EMPLOYEE', temporaryPassword: 'temporary-pr11' });
  await page.goto('/admin/staff');
  await page.getByRole('button', { name: 'Actions for PR11 Counter', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Full name', { exact: true }).fill('PR11 Evening Counter');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const row = page.getByRole('row').filter({ hasText: 'PR11 Evening Counter' });
  await row.getByRole('button', { name: 'Reset password', exact: true }).click();
  await page.getByLabel('Temporary password', { exact: true }).fill('replacement-pr11');
  await page.getByLabel('Confirm password', { exact: true }).fill('replacement-pr11');
  await page.getByRole('dialog').getByRole('button', { name: 'Reset password', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const read = (await apiGet<StaffUser[]>(page.request, '/api/v1/users')).find(u => u.id === user.id)!;
  expect(read.fullName).toBe('PR11 Evening Counter');
  expect(read.mustChangePassword).toBe(true);
  // Staff with activity must archive; a login makes the reset account historical.
  const login = await page.context().request.post('/api/v1/auth/login', { data: { username: 'pr11-counter', password: 'replacement-pr11' } });
  expect(login.ok()).toBe(true);
  await signIn(OWNER);
  await page.goto('/admin/staff');
  await page.getByRole('button', { name: 'Actions for PR11 Evening Counter', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Archive', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Archive', exact: true }).click();
  await expect(row).toHaveCount(0);
  await page.getByLabel(/Show archived/).check();
  await page.getByRole('listitem').filter({ hasText: 'PR11 Evening Counter' }).getByRole('button', { name: 'Restore', exact: true }).click();
  await expect(row).toContainText('inactive');
  const unused = await apiPost<StaffUser>(page.request, '/api/v1/users', { username: 'pr11-unused', fullName: 'PR11 unused', role: 'EMPLOYEE', temporaryPassword: 'temporary-pr11' });
  await page.reload();
  await page.getByRole('button', { name: 'Actions for PR11 unused', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Delete', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('cannot be undone');
  await page.getByRole('button', { name: 'Delete permanently', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  expect((await apiGet<SetupItem[]>(page.request, '/api/v1/setup/staff')).some(u => u.id === unused.id)).toBe(false);
});

