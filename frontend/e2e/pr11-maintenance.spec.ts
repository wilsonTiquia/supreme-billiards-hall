    await expect(page.getByText(/HELP\.md/)).toHaveCount(0);
    const owner = page.getByRole('row').filter({ hasText: 'Owner' });
    await expect(owner.getByRole('button', { name: 'Reset password', exact: true })).toBeDisabled();
    await owner.getByRole('button', { name: 'Actions for Owner', exact: true }).click();
    const archive = page.getByRole('menuitem', { name: /^Archive/ });
    await expect(archive).toHaveAttribute('aria-disabled', 'true');
    await expect(archive).toContainText('You cannot archive yourself.');
    await archive.focus();
