test('loading, failed eligibility, list failures and empty staff remain usable', async ({ page, signIn }) => {
  await maintenanceFixtures(page);
  await signIn(OWNER);
  let release!: () => void;
  const delayed = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/api/v1/tables', async route => {
    await delayed;
    await route.fulfill({ status: 500, json: { success: false, message: 'Tables temporarily unavailable.' } });
  });
  await page.goto('/admin/tables');
  await expect(page.getByRole('status').filter({ hasText: 'Loading tables…' })).toBeVisible();
  release();
  await expect(page.getByRole('alert')).toContainText('Tables temporarily unavailable.');
  await page.route('**/api/v1/setup/staff', route => route.fulfill({ status: 500, json: { success: false, message: 'Could not check staff eligibility.' } }));
  await page.goto('/admin/staff');
  await page.getByRole('button', { name: 'Actions for Front Counter', exact: true }).click();
  await expect(page.getByRole('menuitem', { name: 'Checking…', exact: true })).toHaveAttribute('aria-disabled', 'true');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('alert')).toContainText('Could not check staff eligibility.');
  await expect(page.getByRole('button', { name: 'Retry', exact: true })).toBeEnabled();
  await page.route('**/api/v1/users', route => route.fulfill({ json: { success: true, data: [] } }));
  await page.reload();
  await expect(page.getByText('Nobody can sign in yet.', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'New staff', exact: true })).toBeEnabled();
});


test('dense tables keep help and menus inside a short phone viewport', async ({ page, signIn }) => {
  await page.setViewportSize({ width: 400, height: 480 });
  await maintenanceFixtures(page);
  const dense = Array.from({ length: 60 }, (_, i) => ({ ...tables[1]!, id: `table-${i}`, name: `Practice table ${i + 1}` }));
  await page.route('**/api/v1/tables', route => route.fulfill({ json: { success: true, data: { tables: dense, serverNow: new Date().toISOString() } } }));
  await signIn(OWNER);
  await page.goto('/admin/tables');
  const help = page.getByRole('button', { name: 'Rate details for Practice table 60', exact: true });
  await help.scrollIntoViewIfNeeded();
  await help.click();
  const tooltip = page.getByRole('tooltip');
  await expect(tooltip).toContainText('₱2.1234');
  await expect(tooltip).toContainText('₱127.404');
  const bounds = await tooltip.boundingBox();
  expect(bounds).not.toBeNull();
  expect(bounds!.x).toBeGreaterThanOrEqual(0);
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(400);
  expect(bounds!.y).toBeGreaterThanOrEqual(0);
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(480);
  await page.getByRole('button', { name: 'Actions for Practice table 60', exact: true }).click();
  await expect(page.getByRole('menuitem', { name: 'Edit', exact: true })).toBeInViewport();
  await page.keyboard.press('Escape');
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 400);
});
